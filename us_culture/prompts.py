def build_user_prompt(audience: str, product_line: str, market: str, topics_text: str) -> str:
    return (
        f"市场：{market}\n"
        f"用户群：{audience}\n"
        f"产品线：{product_line}\n\n"
        "今日美区热点：\n"
        f"{topics_text}\n"
    )
